/// The vendored grammars (exact upstream pins; see build.rs).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BundledLanguage {
    JavaScript,
    Typescript,
    Markdown,
    MarkdownInline,
    Zig,
}

extern "C" {
    fn tree_sitter_javascript() -> *const ();
    fn tree_sitter_typescript() -> *const ();
    fn tree_sitter_markdown() -> *const ();
    fn tree_sitter_markdown_inline() -> *const ();
    fn tree_sitter_zig() -> *const ();
}

impl BundledLanguage {
    /// The grammar's `tree_sitter_*` entry point (linked by build.rs).
    fn language(self) -> Language {
        use tree_sitter_language::LanguageFn;
        let f: unsafe extern "C" fn() -> *const () = match self {
            BundledLanguage::JavaScript => tree_sitter_javascript,
            BundledLanguage::Typescript => tree_sitter_typescript,
            BundledLanguage::Markdown => tree_sitter_markdown,
            BundledLanguage::MarkdownInline => tree_sitter_markdown_inline,
            BundledLanguage::Zig => tree_sitter_zig,
        };
        // SAFETY: the function is generated from a grammar by the
        // tree-sitter CLI and linked statically by build.rs.
        Language::from(unsafe { LanguageFn::from_raw(f) })
    }
}

