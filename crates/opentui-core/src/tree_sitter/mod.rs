//! The tree-sitter integration — port of
//! `packages/core/src/lib/tree-sitter/` (client.ts + parser.worker.ts +
//! default-parsers.ts) and `tree-sitter-styled-text.ts` (in [`chunks`]).
//!
//! # Architecture choice (mechanism ≠ upstream, output == upstream)
//!
//! Upstream runs tree-sitter in a **worker thread**: `web-tree-sitter`
//! (wasm core 0.25.10) loads per-language `.wasm` grammars + `.scm`
//! queries shipped in the npm package `assets/`
//! (default-parsers.ts:19-65; parsers-config.ts pins: javascript
//! v0.25.0, typescript v0.23.2, markdown/markdown_inline v0.5.1, zig
//! v1.1.2).
//!
//! The Rust port **links the same grammars as C sources, compiled
//! in-process** (vendored under `third_party/tree-sitter-grammars/` at
//! exactly those tags — see build.rs), runs the byte-identical `.scm`
//! queries (`include_str!` from the spec's own assets), against the
//! `tree-sitter` crate 0.25.10 — the SAME C core version as
//! web-tree-sitter 0.25.10's wasm. Parse trees, capture order and
//! highlight tuples therefore match the oracle's exactly (pinned by the
//! frozen highlight corpus,
//! `crates/opentui-core/tests/data/highlight-corpus.json`, generated by
//! `tools/diff/js/highlight-corpus.ts` from the real package).
//!
//! There is no worker: upstream's worker exists to keep parsing off the
//! UI thread; the port's renderer is synchronous, and the differential
//! oracle compares the SETTLED frame (after `flush()`), where upstream's
//! async highlight has landed — a synchronous highlight reaches the same
//! settled pixels without the frame-count nondeterminism. This mirrors
//! opencode-rust's `oc-syntax` approach (crate-pinned grammars, vendored
//! queries) but pins to opentui 0.5.14's own grammar pins rather than
//! v2's (v2 pins e.g. javascript 0.23.1; opentui 0.5.14 ships 0.25.0).
//!
//! One observable divergence class is handled explicitly: web-tree-sitter
//! reports node offsets as **UTF-16 code-unit indices** (JS string
//! indices — verified against the oracle with CJK/emoji content), while
//! the Rust crate reports byte offsets; [`Utf16Map`] converts at the
//! boundary so `SimpleHighlight` offsets are UTF-16 like the oracle's.

