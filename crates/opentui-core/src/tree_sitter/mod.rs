/// `addDefaultParsers(parsers)` — client.ts:61-68: replaces same-filetype
/// entries in the global override list (applied over the defaults at
/// initialize, client.ts:335-349: overrides win, defaulted filetypes not
/// in overrides kept).
pub fn add_default_parsers(parsers: Vec<FiletypeParserOptions>) {
    let mut overrides = default_parser_overrides()
        .lock()
        .expect("tree-sitter overrides");
    for parser in parsers {
        overrides.retain(|existing| existing.filetype != parser.filetype);
        overrides.push(parser);
    }
}

fn default_parser_overrides() -> &'static Mutex<Vec<FiletypeParserOptions>> {
    static OVERRIDES: OnceLock<Mutex<Vec<FiletypeParserOptions>>> = OnceLock::new();
    OVERRIDES.get_or_init(|| Mutex::new(Vec::new()))
}

