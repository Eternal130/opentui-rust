/// A language the client can load — either a vendored grammar or a
/// consumer-supplied one (`addDefaultParsers` accepts raw language
/// functions in the Rust port where upstream accepts `.wasm` paths;
/// documented mechanism divergence).
#[derive(Clone, Copy)]
pub enum LanguageProvider {
    Bundled(BundledLanguage),
    Raw(tree_sitter_language::LanguageFn),
}

impl LanguageProvider {
    fn language(self) -> Language {
        match self {
            LanguageProvider::Bundled(b) => b.language(),
            LanguageProvider::Raw(f) => Language::from(f),
        }
    }
}

