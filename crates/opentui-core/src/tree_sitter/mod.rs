// SAFETY: the singleton lives for the process lifetime; queries are
// immutable after compilation and Parser use is serialized behind the
// global Mutex (one highlight at a time), matching upstream's single
// long-lived worker.
unsafe impl Send for TreeSitterClient {}
unsafe impl Sync for TreeSitterClient {}

/// A capture in document UTF-16 space, carrying the pattern `#set!`
/// properties the worker reads (conceal / conceal_lines,
/// parser.worker.ts:747-748).
struct RawCapture {
    start_u16: usize,
    end_u16: usize,
    name: String,
    /// set when produced by an injected query pass (document-space
    /// offsets already applied; setProperties came from the injected
    /// query — worker:744-748)
    injected_language: Option<String>,
    conceal: Option<String>,
    conceal_lines: Option<String>,
}

impl TreeSitterClient {
    pub fn new(options: TreeSitterClientOptions) -> Self {
        let _ = options; // in-process: nothing to configure (see module docs)
        TreeSitterClient {
            filetype_options: HashMap::new(),
            filetype_aliases: HashMap::new(),
            parsers: HashMap::new(),
            initialized: false,
        }
    }

    /// `initialize` + `registerDefaultParsers` (client.ts:261-349):
    /// defaults minus overridden filetypes, then overrides.
    pub fn initialize(&mut self) {
        if self.initialized {
            return;
        }
        let overrides = default_parser_overrides()
            .lock()
            .expect("tree-sitter overrides")
            .clone();
        let overridden: std::collections::HashSet<String> =
            overrides.iter().map(|p| p.filetype.clone()).collect();
        for parser in default_parser_options()
            .into_iter()
            .filter(|p| !overridden.contains(&p.filetype))
        {
            self.add_filetype_parser(parser);
        }
        for parser in overrides {
            self.add_filetype_parser(parser);
        }
        self.initialized = true;
    }

    /// `addFiletypeParser` → worker `addFiletypeParser`
    /// (parser.worker.ts:120-141): replace same-filetype entry, clean
    /// stale aliases, dedupe aliases, rebuild the alias map.
    pub fn add_filetype_parser(&mut self, options: FiletypeParserOptions) {
        if let Some(previous) = self.filetype_options.get(&options.filetype) {
            for alias in &previous.aliases {
                if self.filetype_aliases.get(alias).map(String::as_str)
                    == Some(options.filetype.as_str())
                {
                    self.filetype_aliases.remove(alias);
                }
            }
        }
        let aliases: Vec<String> = options
            .aliases
            .iter()
            .filter(|a| **a != options.filetype)
            .cloned()
            .collect::<std::collections::HashSet<_>>()
            .into_iter()
            .collect();
        self.filetype_aliases.remove(&options.filetype);
        for alias in &aliases {
            self.filetype_aliases
                .insert(alias.clone(), options.filetype.clone());
        }
        self.parsers.remove(&options.filetype);
        let filetype = options.filetype.clone();
        self.filetype_options
            .insert(filetype, options_with_aliases(options, aliases));
    }

    /// Worker `resolveCanonicalFiletype` (parser.worker.ts:143-149).
    fn resolve_canonical_filetype(&self, filetype: &str) -> String {
        if self.filetype_options.contains_key(filetype) {
            return filetype.to_owned();
        }
        self.filetype_aliases
            .get(filetype)
            .cloned()
            .unwrap_or_else(|| filetype.to_owned())
    }

    /// Worker `loadFiletypeParser` (parser.worker.ts:257-277): lazy
    /// compile of language + queries.
    fn resolve_filetype_parser(&mut self, filetype: &str) -> bool {
        let canonical = self.resolve_canonical_filetype(filetype);
        if self.parsers.contains_key(&canonical) {
            return true;
        }
        let Some(options) = self.filetype_options.get(&canonical).cloned() else {
            return false;
        };
        let language = options.language.language();
        let Ok(highlights) = Query::new(&language, &options.highlights_query) else {
            return false;
        };
        let injections = options
            .injections_query
            .as_ref()
            .and_then(|q| Query::new(&language, q).ok());
        let mut parser = Parser::new();
        if parser.set_language(&language).is_err() {
            return false;
        }
        self.parsers.insert(
            canonical,
            LoadedParser {
                parser,
                highlights,
                injections,
                injection_mapping: options.injection_mapping,
            },
        );
        true
    }

    /// `highlightOnce(content, filetype)` — client.ts:395-422 → worker
    /// `handleOneShotHighlight` (parser.worker.ts:820-879). Synchronous in
    /// the port (see module docs).
    pub fn highlight_once(&mut self, content: &str, filetype: &str) -> HighlightResult {
        if !self.initialized {
            self.initialize();
        }
        let canonical = self.resolve_canonical_filetype(filetype);
        if !self.resolve_filetype_parser(&canonical) {
            // worker: "No parser available for filetype X" warning
            return HighlightResult {
                highlights: None,
                warning: Some(format!("No parser available for filetype {canonical}")),
                error: None,
            };
        }

        // Markdown parser bug workaround (parser.worker.ts:833-835): a
        // trailing "```" needs a newline for closing delimiters to parse.
        let parse_content = if canonical == "markdown" && content.ends_with("```") {
            format!("{content}\n")
        } else {
            content.to_owned()
        };

        self.oneshot_highlight(&canonical, content, &parse_content)
    }

    /// The worker's ONESHOT pipeline with the tree kept alive for the
    /// injection walk (parser.worker.ts:837-878).
    fn oneshot_highlight(
        &mut self,
        canonical: &str,
        _content: &str, // parse_content covers it (workaround appends newline)
        parse_content: &str,
    ) -> HighlightResult {
        let tree = {
            let Some(loaded) = self.parsers.get_mut(canonical) else {
                return HighlightResult {
                    error: Some("No parser available".into()),
                    ..Default::default()
                };
            };
            match loaded.parser.parse(parse_content, None) {
                Some(tree) => tree,
                None => {
                    return HighlightResult {
                        error: Some("Failed to parse content".into()),
                        ..Default::default()
                    }
                }
            }
        };
        let root = tree.root_node();
        let map = Utf16Map::new(parse_content);

        // worker:850 — main highlights captures
        let (highlights_query, has_injections, injection_mapping) = {
            let loaded = self.parsers.get(canonical).expect("parser loaded");
            (
                &loaded.highlights,
                loaded.injections.is_some(),
                loaded.injection_mapping.clone(),
            )
        };
        let mut captures = collect_captures(highlights_query, root, parse_content.as_bytes(), &map);

        // worker:852-866 — injections (markdown)
        let mut injection_ranges: Vec<(usize, usize, String)> = Vec::new();
        if has_injections {
            let injections_query = self
                .parsers
                .get(canonical)
                .and_then(|p| p.injections.as_ref())
                .expect("checked");
            let injection_captures =
                collect_capture_nodes(injections_query, root, parse_content.as_bytes());

            // languageGroups (worker:419-457) — insertion order per language
            let mut language_groups: Vec<(String, Vec<Node<'_>>)> = Vec::new();
            let mut group_index: HashMap<String, usize> = HashMap::new();
            for (node, name) in &injection_captures {
                if name != "injection.content" && !name.contains("injection") {
                    continue;
                }
                let node_type = node.kind();
                let mut target_language: Option<String> = None;
                if let Some(mapping) = &injection_mapping {
                    if let Some(target) = mapping.node_types.get(node_type) {
                        target_language = Some(target.clone());
                    }
                }
                if target_language.is_none() && node_type == "code_fence_content" {
                    if let Some(language_name) = fence_language(*node, parse_content, &map) {
                        let mapped = injection_mapping
                            .as_ref()
                            .and_then(|m| m.info_string_map.get(&language_name).cloned());
                        target_language = Some(mapped.unwrap_or(language_name));
                    }
                }
                if let Some(language) = target_language {
                    match group_index.get(&language) {
                        Some(&i) => language_groups[i].1.push(*node),
                        None => {
                            group_index.insert(language.clone(), language_groups.len());
                            language_groups.push((language, vec![*node]));
                        }
                    }
                }
            }

            // per-language reusable parser + parse + query (worker:460-528);
            // ranges recorded only for languages WITH a parser.
            for (language, nodes) in language_groups {
                if !self.resolve_filetype_parser(&language) {
                    continue; // worker warns and skips the group
                }
                for injection_node in nodes {
                    let start_u16 = map.utf16_of_byte(injection_node.start_byte());
                    let end_u16 = map.utf16_of_byte(injection_node.end_byte());
                    injection_ranges.push((start_u16, end_u16, language.clone()));
                    let injection_content = map.slice(parse_content, start_u16, end_u16);
                    let sub_map = Utf16Map::new(injection_content);
                    let sub_tree = {
                        let Some(loaded) = self.parsers.get_mut(&language) else {
                            continue;
                        };
                        match loaded.parser.parse(injection_content, None) {
                            Some(t) => t,
                            None => continue,
                        }
                    };
                    let injected_query = &self
                        .parsers
                        .get(&language)
                        .expect("injected parser loaded")
                        .highlights;
                    let sub_captures = collect_captures(
                        injected_query,
                        sub_tree.root_node(),
                        injection_content.as_bytes(),
                        &sub_map,
                    );
                    for sub in sub_captures {
                        // offset into document space (worker:499-514)
                        captures.push(RawCapture {
                            start_u16: sub.start_u16 + start_u16,
                            end_u16: sub.end_u16 + start_u16,
                            name: sub.name,
                            injected_language: Some(language.clone()),
                            conceal: sub.conceal,
                            conceal_lines: sub.conceal_lines,
                        });
                    }
                }
            }
        }

        // getSimpleHighlights (worker:714-775)
        let mut highlights: Vec<SimpleHighlight> = Vec::new();
        for capture in captures {
            let mut meta = HighlightMeta::default();
            if capture.injected_language.is_none() {
                for (start, end, lang) in &injection_ranges {
                    if capture.start_u16 >= *start && capture.end_u16 <= *end {
                        meta.is_injection = true;
                        meta.injection_lang = Some(lang.clone());
                        break;
                    }
                    if capture.start_u16 <= *start && capture.end_u16 >= *end {
                        meta.contains_injection = true;
                        break;
                    }
                }
            } else {
                // injected captures are inside their ranges by construction
                meta.is_injection = true;
                meta.injection_lang = capture.injected_language.clone();
            }
            if let Some(conceal) = &capture.conceal {
                meta.conceal = Some(conceal.clone());
            }
            if let Some(lines) = &capture.conceal_lines {
                meta.conceal_lines = Some(lines.clone());
            }
            if meta.is_empty() {
                highlights.push(SimpleHighlight::bare(
                    capture.start_u16,
                    capture.end_u16,
                    &capture.name,
                ));
            } else {
                highlights.push(SimpleHighlight {
                    start: capture.start_u16,
                    end: capture.end_u16,
                    group: capture.name,
                    meta,
                });
            }
        }

        // worker:772 — stable sort by start (JS sort is stable)
        highlights.sort_by_key(|h| h.start);
        HighlightResult {
            highlights: Some(highlights),
            warning: None,
            error: None,
        }
    }
}

fn options_with_aliases(
    options: FiletypeParserOptions,
    aliases: Vec<String>,
) -> FiletypeParserOptions {
    FiletypeParserOptions {
        filetype: options.filetype,
        aliases,
        language: options.language,
        highlights_query: options.highlights_query,
        injections_query: options.injections_query,
        injection_mapping: options.injection_mapping,
    }
}

/// Collect `query.captures(root)` in engine order — the same C entry
/// point web-tree-sitter 0.25.10 drives (`_ts_query_captures_wasm`), so
/// capture order matches. Byte offsets convert to UTF-16 via `map`.
fn collect_captures(
    query: &Query,
    root: Node<'_>,
    text_bytes: &[u8],
    map: &Utf16Map,
) -> Vec<RawCapture> {
    let mut out = Vec::new();
    let mut cursor = QueryCursor::new();
    let mut iter = cursor.captures(query, root, text_bytes);
    while let Some((m, capture_index)) = iter.next() {
        let cap = &m.captures[*capture_index];
        let name = query.capture_names()[cap.index as usize].to_owned();
        let node = cap.node;
        let (conceal, conceal_lines) = pattern_set_props(query, m.pattern_index);
        out.push(RawCapture {
            start_u16: map.utf16_of_byte(node.start_byte()),
            end_u16: map.utf16_of_byte(node.end_byte()),
            name,
            injected_language: None,
            conceal,
            conceal_lines,
        });
    }
    out
}

/// Same sweep, retaining the `Node` handles (needed for the injection
/// walk while the tree is alive — parser.worker.ts:414-457).
fn collect_capture_nodes<'t>(
    query: &Query,
    root: Node<'t>,
    text_bytes: &[u8],
) -> Vec<(Node<'t>, String)> {
    let mut out = Vec::new();
    let mut cursor = QueryCursor::new();
    let mut iter = cursor.captures(query, root, text_bytes);
    while let Some((m, capture_index)) = iter.next() {
        let cap = &m.captures[*capture_index];
        let name = query.capture_names()[cap.index as usize].to_owned();
        out.push((cap.node, name));
    }
    out
}

/// `#set! conceal` / `#set! conceal_lines` for a pattern — web-tree-sitter
/// `query.setProperties[patternIndex]` (tree-sitter.cjs:3286) read by the
/// worker (parser.worker.ts:747-748).
fn pattern_set_props(query: &Query, pattern_index: usize) -> (Option<String>, Option<String>) {
    let mut conceal = None;
    let mut conceal_lines = None;
    for prop in query.property_settings(pattern_index) {
        if prop.key.as_ref() == "conceal" {
            conceal = prop.value.as_deref().map(String::from);
        } else if prop.key.as_ref() == "conceal_lines" {
            conceal_lines = prop.value.as_deref().map(String::from);
        }
    }
    (conceal, conceal_lines)
}

/// The `code_fence_content` → parent `fenced_code_block` → `info_string`
/// → `language` node text walk (parser.worker.ts:430-448).
fn fence_language(node: Node<'_>, content: &str, map: &Utf16Map) -> Option<String> {
    let parent = node.parent()?;
    let info_string = (0..parent.child_count())
        .filter_map(|i| parent.child(i))
        .find(|c| c.kind() == "info_string")?;
    let language_node = (0..info_string.child_count())
        .filter_map(|i| info_string.child(i))
        .find(|c| c.kind() == "language")?;
    let text = map.slice(
        content,
        map.utf16_of_byte(language_node.start_byte()),
        map.utf16_of_byte(language_node.end_byte()),
    );
    Some(text.to_owned())
}

/// UTF-16 code-unit index map — web-tree-sitter reports node offsets in
/// UTF-16 (JS string indices); the Rust crate reports byte offsets.
pub struct Utf16Map {
    utf16_of: Vec<usize>,
    byte_of: Vec<usize>,
}

impl Utf16Map {
    #[must_use]
    pub fn new(content: &str) -> Self {
        let mut utf16_of = vec![0usize; content.len() + 1];
        let mut byte_of = Vec::with_capacity(content.len() + 1);
        let mut u16_pos = 0usize;
        let mut byte_pos = 0usize;
        byte_of.push(0usize);
        for ch in content.chars() {
            let len_utf8 = ch.len_utf8();
            let len_utf16 = ch.len_utf16();
            for i in 1..len_utf8 {
                utf16_of[byte_pos + i] = u16_pos;
            }
            u16_pos += len_utf16;
            byte_pos += len_utf8;
            utf16_of[byte_pos] = u16_pos;
            for _ in 0..len_utf16 {
                byte_of.push(byte_pos);
            }
        }
        Utf16Map { utf16_of, byte_of }
    }

    #[must_use]
    pub fn utf16_of_byte(&self, byte: usize) -> usize {
        self.utf16_of[byte.min(self.utf16_of.len() - 1)]
    }

    #[must_use]
    pub fn byte_of_utf16(&self, u16_index: usize) -> usize {
        self.byte_of[u16_index.min(self.byte_of.len() - 1)]
    }

    /// Total UTF-16 length (`content.length`).
    #[must_use]
    pub fn total_utf16(&self) -> usize {
        self.byte_of.len() - 1
    }

    /// `content.slice(start, end)` with UTF-16 indices.
    pub fn slice<'a>(&self, content: &'a str, start: usize, end: usize) -> &'a str {
        let b0 = self.byte_of[start.min(self.byte_of.len() - 1)];
        let b1 = self.byte_of[end.min(self.byte_of.len() - 1)]
            .max(b0)
            .min(content.len());
        &content[b0..b1]
    }
}

/// `getTreeSitterClient()` — index.ts:22-60: the process singleton.
pub fn get_tree_sitter_client() -> &'static Mutex<TreeSitterClient> {
    static CLIENT: OnceLock<Mutex<TreeSitterClient>> = OnceLock::new();
    CLIENT.get_or_init(|| Mutex::new(TreeSitterClient::new(TreeSitterClientOptions::default())))
}

/// `destroyTreeSitterClient()` — index.ts:62-75. The in-process port
/// resets the singleton (drops parsers/queries) and the overrides.
pub fn destroy_tree_sitter_client() {
    if let Ok(mut client) = get_tree_sitter_client().lock() {
        *client = TreeSitterClient::new(TreeSitterClientOptions::default());
    }
    default_parser_overrides()
        .lock()
        .expect("tree-sitter overrides")
        .clear();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn utf16_map_ascii_and_unicode() {
        let m = Utf16Map::new("abc");
        assert_eq!(m.utf16_of_byte(0), 0);
        assert_eq!(m.utf16_of_byte(3), 3);
        assert_eq!(m.slice("abc", 1, 3), "bc");

        // 中 = 3 bytes / 1 utf16 unit; 🙂 = 4 bytes / 2 utf16 units
        let s = "a中🙂b";
        let m = Utf16Map::new(s);
        assert_eq!(m.utf16_of_byte(0), 0); // a
        assert_eq!(m.utf16_of_byte(1), 1); // 中
        assert_eq!(m.utf16_of_byte(4), 2); // 🙂
        assert_eq!(m.utf16_of_byte(8), 4); // b
        assert_eq!(m.utf16_of_byte(9), 5); // end
        assert_eq!(m.slice(s, 1, 2), "中");
        assert_eq!(m.slice(s, 2, 4), "🙂");
        assert_eq!(m.slice(s, 1, 5), "中🙂b");
        assert_eq!(m.byte_of_utf16(4), 8);
    }

    #[test]
    fn client_initializes_defaults_and_resolves_aliases() {
        let mut client = TreeSitterClient::new(TreeSitterClientOptions::default());
        client.initialize();
        // alias resolution (worker resolveCanonicalFiletype)
        assert_eq!(
            client.resolve_canonical_filetype("typescriptreact"),
            "typescript"
        );
        assert_eq!(
            client.resolve_canonical_filetype("javascriptreact"),
            "javascript"
        );
        assert_eq!(client.resolve_canonical_filetype("cobol"), "cobol");
        // parsers load for the 5 defaults, not for unknown
        assert!(client.resolve_filetype_parser("markdown"));
        assert!(!client.resolve_filetype_parser("rust"));
    }
}
