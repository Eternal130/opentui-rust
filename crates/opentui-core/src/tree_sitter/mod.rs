/// `SimpleHighlight` — lib/tree-sitter/types.ts (the `[start, end, group,
/// meta?]` tuple): offsets are **UTF-16 code units** (the JS side slices
/// `content` with them).
#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct SimpleHighlight {
    pub start: usize,
    pub end: usize,
    pub group: String,
    #[serde(default, skip_serializing_if = "HighlightMeta::is_empty")]
    pub meta: HighlightMeta,
}

/// The meta object (worker getSimpleHighlights, parser.worker.ts:750-763).
#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HighlightMeta {
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub is_injection: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub injection_lang: Option<String>,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub contains_injection: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub conceal: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub conceal_lines: Option<String>,
}

impl HighlightMeta {
    fn is_empty(&self) -> bool {
        !self.is_injection
            && self.injection_lang.is_none()
            && !self.contains_injection
            && self.conceal.is_none()
            && self.conceal_lines.is_none()
    }
}

impl SimpleHighlight {
    fn bare(start: usize, end: usize, group: &str) -> Self {
        SimpleHighlight {
            start,
            end,
            group: group.to_owned(),
            meta: HighlightMeta::default(),
        }
    }
}

